/// marker class for event receivers
interface class IEventReceiver {}

@module
abstract class EventBusModule {
  @singleton
  EventBus get eventBus => EventBus();
}

/// [EventBase] is the base class for all events in the app. Event data are
/// immutable.
@immutable
abstract class EventBase<T extends Object?> {
  /// EventBase can store a data object of any type, but is not required to
  final T? data;
  final IEventReceiver? replyTo; // if this event is the origin of a request
  // for a service, set replyTo to this. The generated response will include
  // the same value in replyTo.

  /// [EventBase] constructor with an optional sender (if the response should be
  /// addressed to the sender), and optional data of any type
  const EventBase({this.replyTo, this.data});

  /// once an event is created, using event.emit will send the event to the
  /// event bus; this getter returns the event.
  EventBase get emit => this.also((it) => sl<EventBus>().fire(it));
}

