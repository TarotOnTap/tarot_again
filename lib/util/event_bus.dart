typedef EventHandler<EventType extends EventBase> =
    void Function(EventType event);
typedef EventFilter<EventType extends EventBase> =
    bool Function(EventType event);

typedef SubscriptionMap<EventType extends EventBase> =
    IMap<EventType, StreamSubscription<EventType>>;

mixin EventReceiverMixin implements IEventReceiver {
  SubscriptionMap _subscriptionMap = const SubscriptionMap.empty();

  bool selfEventFilter<EventType extends EventBase>(EventType event) {
    return event.replyTo == this;
  }

  void setHandler<U extends EventBase>({
    required U eventType,
    required EventHandler<U> handler,
    EventFilter? filter,
  }) {
    final receiver = receiveEvents<U>(onData: handler, filter: filter);
    _subscriptionMap = _subscriptionMap.add(eventType, receiver);
    // subscriptionMap.add(U, ( receiveEvents(onData: handler)(event, receiveEvent) {
  }

  void cancelReceiver<U extends EventBase>(U eventType) {
    final StreamSubscription? receiver = _subscriptionMap[eventType];
    receiver?.cancel();
    _subscriptionMap = _subscriptionMap.remove(eventType);
  }

  void dispose() {
    _subscriptionMap.forEach((eventType, receiver) {
      receiver.cancel();
    });
    _subscriptionMap = const SubscriptionMap.empty();
  }
}

